#!/usr/bin/env python3
"""Baseline datapath test using ONLY the traffic generator (no synthesized NF).

Answers "is the testbed itself healthy?" before any loss is blamed on a synthesized
NF. It runs the hand-written, known-good traffic-generator P4 on BOTH switches:

  - TG switch: floods/steers pktgen traffic to the DUT (broadcast = dut_ports),
    exactly like a real throughput experiment.
  - DUT switch: instead of a synapse-synthesized NF, it runs the traffic-generator
    too, configured with plain forwarding rules to reproduce a chosen datapath:
        --mode echo     : each packet goes back out the SAME port (A -> A), the
                          pattern of an NF that replies to the sender, on a
                          known-good dataplane (unicast forward to the ingress port).
        --mode forward  : each packet goes out a DIFFERENT port (A <-> B pairs),
                          the pattern every other NF (e.g. map_table) uses.

Then it runs the standard throughput search and prints TX/RX/loss.

Interpretation, when a synthesized NF on one of these datapaths is losing packets:
  - the same datapath loses here too     -> the testbed is at fault, not the NF:
    the loss reproduces with a known-good dataplane. Look at TG/DUT config,
    TM/mcast, or the measurement itself.
  - this is clean                        -> the synthesized NF or its controller
    is the culprit.
  - both modes lose                      -> something more fundamental in the
    baseline steering/measurement.
"""

import argparse
import tomli

from pathlib import Path

from hosts.tofino_tg import TofinoTG, TofinoTGController
from hosts.pktgen import Pktgen, TrafficDist
from experiments.experiment import Experiment
from utils.kill_hosts import kill_hosts_on_sigint
from utils.constants import EVAL_DIR

# The throughput experiments' traffic profile, so the numbers compare directly.
PACKET_SIZE = 256
TOTAL_FLOWS = 40_000


def build_routes(mode: str, client_ports: list[int]) -> list[tuple[int, int]]:
    """Return (ingress, egress) forwarding pairs for the DUT traffic generator."""
    if mode == "echo":
        # A -> A: send every packet back out the port it arrived on.
        return [(p, p) for p in client_ports]

    # forward: A <-> B, pairing consecutive ports (3<->4, 5<->6, ...).
    routes: list[tuple[int, int]] = []
    ports = list(client_ports)
    for i in range(0, len(ports) - 1, 2):
        a, b = ports[i], ports[i + 1]
        routes.append((a, b))
        routes.append((b, a))
    if len(ports) % 2 == 1:
        # Odd count: last port echoes itself so no traffic is silently dropped.
        routes.append((ports[-1], ports[-1]))
    return routes


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("-c", "--config-file", type=Path, default=EVAL_DIR / "experiment_config.toml", help="Path to config file")
    parser.add_argument("--mode", choices=["echo", "forward"], default="echo", help="DUT datapath to test (default: echo)")
    parser.add_argument("--pkt-size", type=int, default=PACKET_SIZE, help="Packet size in bytes")
    parser.add_argument("--flows", type=int, default=TOTAL_FLOWS, help="Number of flows generated by pktgen")
    parser.add_argument("--dns-mode", action="store_true", default=False,
                        help="pktgen DNS mode: flows are client-server pairs announced by DNS responses (meta4's traffic)")
    parser.add_argument("--domains", type=str, default=None,
                        help="DNS mode: domains file, as a path on the pktgen host (default: dpdk-nfs/meta4/domains.txt in its repo)")
    parser.add_argument("--dns-ratio", type=float, default=0.0014, help="DNS mode: fraction of packets that are DNS responses")
    args = parser.parse_args()

    with open(args.config_file, "rb") as f:
        config = tomli.load(f)

    kill_hosts_on_sigint(config)

    hosts = config["hosts"]
    repos = config["repo"]
    tg = config["devices"]["switch_tg"]
    dut = config["devices"]["switch_dut"]
    logs = config["logs"]

    tg_dut_ports = list(tg["dut_ports"])
    client_ports = list(dut["client_ports"])
    routes = build_routes(args.mode, client_ports)

    tg_switch = TofinoTG(hosts["switch_tg"], repos["switch_tg"], tg["sde"], tg["tofino_version"], log_file=logs["switch_tg"])
    tg_controller = TofinoTGController(hosts["switch_tg"], repos["switch_tg"], tg["sde"], log_file=logs["controller_tg"])
    dut_switch = TofinoTG(hosts["switch_dut"], repos["switch_dut"], dut["sde"], dut["tofino_version"], log_file=logs["switch_dut"])
    dut_controller = TofinoTGController(hosts["switch_dut"], repos["switch_dut"], dut["sde"], log_file=logs["controller_dut"])
    pktgen = Pktgen(
        hostname=hosts["pktgen"],
        repo=repos["pktgen"],
        rx_pcie_dev=config["devices"]["pktgen"]["rx_dev"],
        tx_pcie_dev=config["devices"]["pktgen"]["tx_dev"],
        nb_tx_cores=config["devices"]["pktgen"]["nb_tx_cores"],
        log_file=logs["pktgen"],
    )

    try:
        # Bring up the traffic generator on both switches.
        tg_switch.install()
        dut_switch.install()
        tg_switch.launch()
        dut_switch.launch()
        tg_switch.wait_ready()
        dut_switch.wait_ready()

        # TG: flood/steer pktgen traffic to all DUT ports (same as a real experiment).
        tg_controller.setup(broadcast=tg_dut_ports, symmetric=[], route=[])

        # DUT: plain forwarding rules that reproduce the chosen datapath. The
        # broadcast group (client_ports) is only used by route_tg on the DUT's
        # port 1 (server port), which sees no traffic here -- it just avoids an
        # empty multicast group; the routing is done entirely by `route`.
        dut_controller.setup(broadcast=client_ports, symmetric=[], route=routes)

        domains = args.domains or str(Path(repos["pktgen"]) / "dpdk-nfs" / "meta4" / "domains.txt")
        pktgen.launch(
            nb_flows=args.flows,
            traffic_dist=TrafficDist.UNIFORM,
            pkt_size=args.pkt_size,
            kvs_mode=False,
            dns_mode=args.dns_mode,
            domains=domains,
            dns_ratio=args.dns_ratio,
        )
        pktgen.wait_launch()

        exp = Experiment(name=f"Baseline ({args.mode}, traffic-generator DUT)", log_file=logs["experiment"], iterations=1)
        report = exp.find_stable_throughput(tg_controller=tg_controller, pktgen=pktgen, churn=0)

        tx_Gbps = report.dut_ingress_bps / 1e9
        tx_Mpps = report.dut_ingress_pps / 1e6
        rx_Gbps = report.dut_egress_bps / 1e9
        rx_Mpps = report.dut_egress_pps / 1e6

        print(f"Baseline mode: {args.mode}  (DUT = traffic-generator, no synthesized NF)  pktgen: {'DNS mode' if args.dns_mode else 'plain'}")
        print(f"TX     {tx_Mpps:12.5f} Mpps {tx_Gbps:12.5f} Gbps")
        print(f"RX     {rx_Mpps:12.5f} Mpps {rx_Gbps:12.5f} Gbps")
        print(f"Loss   {report.loss * 100:.3f}%")
    finally:
        try:
            pktgen.close()
        except Exception:
            pass
        for switch in (tg_switch, dut_switch):
            try:
                switch.kill_switchd()
            except Exception:
                pass


if __name__ == "__main__":
    main()
